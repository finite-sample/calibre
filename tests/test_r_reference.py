# Monotone P-spline vs R's scam
# --------------------------------------------------------------------------- #

_SCAM = _load("scam_reference.json")["cases"]


@pytest.mark.parametrize("name", sorted(_SCAM))
def test_monotone_spline_agrees_with_scam(name):
    """The monotone spline must track ``scam(bs="mpi")``.

    ``scam`` implements the same construction -- a B-spline basis with a discrete
    coefficient penalty, reparameterised so the coefficients increase (Pya & Wood
    2015). So it is the right external reference.

    A tight pointwise bound would be the wrong assertion, and measuring it showed
    why. ``scam`` selects its smoothing parameter by GCV while calibre
    cross-validates log-loss, so the two legitimately land on differently smoothed
    curves -- and on two of these three cases *calibre* achieves the lower
    in-sample log-loss (``steep``: 0.4122 vs 0.4160; ``logistic``: 0.60334 vs
    0.60335). Demanding pointwise agreement would penalise the better fit.

    Divergence concentrates where it should: at the boundaries, where the two
    packages' extrapolation conventions differ and the data is thinnest. On
    ``concave`` (true ``p = sqrt(x)``, so ``p -> 0`` steeply at the left edge) the
    curves differ by 0.117 at ``x = 0.001`` but only 0.060 in the interior.

    So what is checked is what is actually claimed: both fits are monotone, and
    they agree in the interior. Proper-score competitiveness is asserted separately
    by :func:`test_monotone_spline_log_loss_matches_scam`.
    """
    from calibre import SplineCalibrator

    case = _SCAM[name]
    x = np.asarray(case["x"], dtype=float)
    y = np.asarray(case["y"], dtype=float)
    grid = np.asarray(case["grid"], dtype=float)
    reference = np.asarray(case["fitted_grid"], dtype=float)

    cal = SplineCalibrator(n_knots=10, degree=3, random_state=0).fit(x, y)
    fitted = cal.transform(grid)

    assert np.all(np.diff(fitted) >= -1e-10), "calibre fit is not monotone"
    assert np.all(np.diff(reference) >= -1e-9), "scam reference is not monotone"

    interior = (grid >= np.quantile(x, 0.05)) & (grid <= np.quantile(x, 0.95))
    gap = float(np.max(np.abs(fitted[interior] - reference[interior])))
    assert gap < 0.08, f"{name}: interior curves differ by {gap:.4f}"

    mean_gap = float(np.mean(np.abs(fitted - reference)))
    assert mean_gap < 0.05, f"{name}: mean gap {mean_gap:.4f} across the range"


@pytest.mark.parametrize("name", sorted(_SCAM))
def test_monotone_spline_log_loss_matches_scam(name):
    """In-sample log-loss must be comparable to scam's, not merely finite."""
    from calibre import SplineCalibrator

    case = _SCAM[name]
    x = np.asarray(case["x"], dtype=float)
    y = np.asarray(case["y"], dtype=float)
    reference_loss = float(np.atleast_1d(case["logloss"])[0])

    fitted = SplineCalibrator(n_knots=10, degree=3, random_state=0).fit_transform(x, y)
    p = np.clip(fitted, 1e-12, 1 - 1e-12)
    ours = float(-np.mean(y * np.log(p) + (1 - y) * np.log1p(-p)))

    assert ours < reference_loss * 1.05, (
        f"{name}: log-loss {ours:.6f} vs scam {reference_loss:.6f}"
    )
