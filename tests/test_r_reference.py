@pytest.mark.parametrize("name", sorted(PAVA))
def test_cir_knots_are_strictly_increasing(name):
    """CIR's guarantee: no two knots share a value, so no interior plateau.

    This is the package's headline claim, stated on the object CIR actually
    produces. Testing "no repeated value in transform(unique(x))" instead would
    be wrong: the terminal blocks are legitimately flat and can span many
    points, which is why the curve is only strictly monotone *between* the first
    and last knots.

    A plateau-preserving implementation satisfies calibre's current granularity
    test (ratio >= 0.003) while failing this one.
    """
    from calibre import CenteredIsotonicCalibrator

    x, y, w = _case(name)
    if len(np.unique(y)) < 2:
        pytest.skip("constant target: the curve is legitimately flat")

    cal = CenteredIsotonicCalibrator().fit(x, y, sample_weight=w)
    knots_x = cal.calibration_curve_.x
    knots_y = cal.calibration_curve_.y

    assert np.all(np.diff(knots_x) > 0), f"{name}: knot grid not increasing: {knots_x}"
    assert np.all(np.diff(knots_y) > 0), (
        f"{name}: CIR produced two knots at the same value, i.e. a plateau "
        f"survived the collapse: {knots_y}"
    )


@pytest.mark.parametrize("name", sorted(PAVA))
def test_cir_is_monotone_and_at_least_as_granular_as_isotonic(name):
    """CIR must stay monotone while producing no fewer distinct values than PAVA.

    The granularity claim reduces to this comparison, and it is the one the
    current suite never makes.
    """
    from calibre import CenteredIsotonicCalibrator, IsotonicCalibrator

    x, y, w = _case(name)
    grid = np.unique(x)

    cir = CenteredIsotonicCalibrator().fit(x, y, sample_weight=w).transform(grid)
    iso = IsotonicCalibrator().fit(x, y).transform(grid)

    assert np.all(np.diff(cir) >= -1e-12), f"{name}: CIR is not monotone: {cir}"
    assert len(np.unique(cir)) >= len(np.unique(iso)), (
        f"{name}: CIR gave {len(np.unique(cir))} distinct values, "
        f"isotonic gave {len(np.unique(iso))}"
    )


# --------------------------------------------------------------------------- #
# Nearly-isotonic regression
# --------------------------------------------------------------------------- #

# calibre minimizes  ||y - b||^2 + lam * sum max(0, b_i - b_{i+1})
# the paper minimizes (1/2)||y - b||^2 + lam_paper * sum max(0, ...)
# so lam_calibre = 2 * lam_paper.
LAMBDA_SCALE = 2.0


def _neariso_points():
    for name, case in NEARISO.items():
        for key, sol in case["solutions"].items():
            lam_paper = float(np.atleast_1d(sol["lambda_paper"])[0])
            if lam_paper <= 0:
                continue  # lambda=0 interpolates the data; nothing to pin
            yield pytest.param(name, key, id=f"{name}-{key}")


@pytest.mark.parametrize("name,key", list(_neariso_points()))
def test_nearly_isotonic_cvx_matches_r_neariso(name, key):
    """The CVXPY solver reproduces R's neariso at the matched lambda."""
    from calibre import NearlyIsotonicCalibrator

    case = NEARISO[name]
    y = np.asarray(case["y"], dtype=float)
    x = np.arange(1.0, len(y) + 1.0)

    sol = case["solutions"][key]
    lam_paper = float(np.atleast_1d(sol["lambda_paper"])[0])
    expected = np.asarray(sol["beta"], dtype=float)

    cal = NearlyIsotonicCalibrator(lam=LAMBDA_SCALE * lam_paper, method="cvx")
    got = cal.fit(x, y).transform(x)
    np.testing.assert_allclose(got, expected, rtol=0, atol=1e-6)


@pytest.mark.parametrize("name,key", list(_neariso_points()))
def test_nearly_isotonic_path_matches_r_neariso(name, key):
    """The path solver must compute the estimator it names.

    Guards finding A6: the shipped path algorithm uses the raw level gap as its
    collision time instead of dividing by the difference in the groups' path
    slopes, and never lets group levels drift with lambda. It therefore does not
    solve the nearly-isotonic problem and disagrees with both R's neariso and
    calibre's own CVXPY solver.
    """
    from calibre import NearlyIsotonicCalibrator

    case = NEARISO[name]
    y = np.asarray(case["y"], dtype=float)
    x = np.arange(1.0, len(y) + 1.0)

    sol = case["solutions"][key]
    lam_paper = float(np.atleast_1d(sol["lambda_paper"])[0])
    expected = np.asarray(sol["beta"], dtype=float)

    cal = NearlyIsotonicCalibrator(lam=LAMBDA_SCALE * lam_paper, method="path")
    got = cal.fit(x, y).transform(x)
    np.testing.assert_allclose(got, expected, rtol=0, atol=1e-6)


@pytest.mark.parametrize("name", sorted(NEARISO))
def test_nearly_isotonic_solvers_agree(name):
    """cvx and path must solve the same problem at the same lambda."""
    from calibre import NearlyIsotonicCalibrator

    y = np.asarray(NEARISO[name]["y"], dtype=float)
    x = np.arange(1.0, len(y) + 1.0)

    for lam in (0.05, 0.2, 0.5, 1.0):
        a = NearlyIsotonicCalibrator(lam=lam, method="cvx").fit(x, y).transform(x)
        b = NearlyIsotonicCalibrator(lam=lam, method="path").fit(x, y).transform(x)
        np.testing.assert_allclose(
            b, a, rtol=0, atol=1e-6, err_msg=f"{name}: solvers disagree at lam={lam}"
        )


@pytest.mark.parametrize("name", sorted(NEARISO))
def test_nearly_isotonic_attains_the_objective(name):
    """Both solvers must attain the documented objective's optimum.

    An independent check that does not rely on R: whatever the solver does, it
    cannot beat -- or fall short of -- the optimum of the objective it claims.
    """
    from calibre import NearlyIsotonicCalibrator

    y = np.asarray(NEARISO[name]["y"], dtype=float)
    x = np.arange(1.0, len(y) + 1.0)

    def objective(b, lam):
        return float(
            np.sum((y - b) ** 2) + lam * np.sum(np.maximum(0.0, b[:-1] - b[1:]))
        )

    for lam in (0.05, 0.2, 0.5, 1.0):
        ref = NearlyIsotonicCalibrator(lam=lam, method="cvx").fit(x, y).transform(x)
        got = NearlyIsotonicCalibrator(lam=lam, method="path").fit(x, y).transform(x)
        assert objective(got, lam) <= objective(ref, lam) + 1e-6, (
            f"{name}: path solver is suboptimal at lam={lam}: "
            f"{objective(got, lam):.8f} > {objective(ref, lam):.8f}"
        )


@pytest.mark.parametrize("key", sorted(NEARISO_OOR.get("solutions", {})))
def test_clipping_is_opt_out_able(key):
    """Output must not be silently clamped to [0, 1] with no way to disable it.

    Five of the calibrators apply a hard-coded post-hoc np.clip(., 0, 1). That
    makes them disagree with their own documented objective on any target
    straying outside the unit interval -- and a clipped solution is not the
    box-constrained optimum either, since the clip happens after the solve
    rather than as a constraint inside it.
    """
    from calibre import NearlyIsotonicCalibrator

    y = np.asarray(NEARISO_OOR["y"], dtype=float)
    x = np.arange(1.0, len(y) + 1.0)
    sol = NEARISO_OOR["solutions"][key]
    lam_paper = float(np.atleast_1d(sol["lambda_paper"])[0])
    expected = np.asarray(sol["beta"], dtype=float)
    assert np.any((expected < 0) | (expected > 1)), "fixture must exercise the clip"

    cal = NearlyIsotonicCalibrator(
        lam=LAMBDA_SCALE * lam_paper, method="cvx", clip_output=False
    )
    got = cal.fit(x, y).transform(x)
    np.testing.assert_allclose(got, expected, rtol=0, atol=1e-6)


def test_lambda_scaling_is_documented():
    """calibre's lam is 2x the paper's lambda; the docstring must say so.

    The class docstring reproduces the paper's objective verbatim while the code
    omits the 1/2 on the squared-error term, so a lambda transferred from the
    paper delivers half the intended regularization.
    """
    from calibre import NearlyIsotonicCalibrator

    doc = (NearlyIsotonicCalibrator.__doc__ or "") + (
        NearlyIsotonicCalibrator.__init__.__doc__ or ""
    )
    lowered = doc.lower()
    assert "1/2" in doc or "\\frac{1}{2}" in doc or "twice" in lowered, (
        "NearlyIsotonicCalibrator's documented objective omits the 1/2 factor "
        "that the reference formulation carries, so `lam` is silently 2x the "
        "paper's lambda. Either match the paper's scaling or document the "
        "difference."
    )


