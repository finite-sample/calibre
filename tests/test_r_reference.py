"""Cross-language reference tests against R implementations.

Fixtures in tests/fixtures/r/ are generated by experiments/r_reference/gen_fixtures.R
and committed, so these tests need no R installation. See that script for the
package versions and for how to build the CRAN-archived `neariso`.

References pinned here:
    stats::isoreg, Iso::pava   -> unweighted PAVA
    isotone::gpava             -> weighted PAVA
    cir::cirPAVA               -> centered isotonic regression
    neariso                    -> nearly-isotonic solution path
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pytest

FIXTURE_DIR = Path(__file__).parent / "fixtures" / "r"


def _load(name: str) -> dict:
    with open(FIXTURE_DIR / name) as fh:
        return json.load(fh)


PAVA = _load("pava_reference.json")["cases"]
_NI = _load("neariso_reference.json")
NEARISO = _NI["cases"]
NEARISO_OOR = _NI["out_of_range"]


def _case(name: str) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    c = PAVA[name]
    return (
        np.asarray(c["x"], dtype=float),
        np.asarray(c["y"], dtype=float),
        np.asarray(c["w"], dtype=float),
    )


# --------------------------------------------------------------------------- #
# Unweighted PAVA
# --------------------------------------------------------------------------- #

# `stats::isoreg` runs PAVA on the y-sequence ordered by x without first pooling
# tied x values, whereas sklearn/calibre pool ties into a single weighted point.
# The two therefore legitimately disagree when x has ties, so those cases are
# checked against the aggregated reference instead (see test_ties_are_pooled).
_UNTIED = ["simple", "binary", "all_zero", "all_one", "decreasing", "n1", "n2"]


@pytest.mark.parametrize("name", _UNTIED)
def test_isotonic_matches_r_isoreg(name):
    """calibre's IsotonicCalibrator reproduces stats::isoreg on distinct x."""
    from calibre import IsotonicCalibrator

    x, y, _ = _case(name)
    expected = np.asarray(PAVA[name]["isoreg"], dtype=float)

    got = IsotonicCalibrator().fit(x, y).transform(x)
    np.testing.assert_allclose(got, expected, rtol=0, atol=1e-10)


@pytest.mark.parametrize("name", _UNTIED)
def test_r_references_agree_with_each_other(name):
    """Sanity check on the fixtures themselves: isoreg == Iso::pava."""
    a = np.asarray(PAVA[name]["isoreg"], dtype=float)
    b = np.asarray(PAVA[name]["iso_pava"], dtype=float)
    np.testing.assert_allclose(a, b, rtol=0, atol=1e-12)


