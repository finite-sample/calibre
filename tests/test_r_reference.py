@pytest.mark.parametrize("name", sorted(PAVA))
def test_weighted_pava_matches_r_gpava(name):
    """The shared weighted-PAVA primitive reproduces isotone::gpava.

    This is the primitive every constrained-isotonic calibrator is built on, so
    it is pinned independently of any calibrator.
    """
    from calibre._core import weighted_pava

    _, y, w = _case(name)
    expected = np.asarray(PAVA[name]["gpava_weighted"], dtype=float)

    got = weighted_pava(y, w)
    np.testing.assert_allclose(got, expected, rtol=0, atol=1e-10)


@pytest.mark.parametrize("name", sorted(PAVA))
def test_weighted_r_references_agree(name):
    """Fixture sanity: isotone::gpava == Iso::pava with weights."""
    a = np.asarray(PAVA[name]["gpava_weighted"], dtype=float)
    b = np.asarray(PAVA[name]["iso_pava_weighted"], dtype=float)
    np.testing.assert_allclose(a, b, rtol=0, atol=1e-10)


@pytest.mark.parametrize("name", sorted(PAVA))
def test_unit_weights_reduce_to_unweighted(name):
    """weighted_pava with w=1 must equal the unweighted reference."""
    from calibre._core import weighted_pava

    _, y, _ = _case(name)
    expected = np.asarray(PAVA[name]["iso_pava"], dtype=float)
    got = weighted_pava(y, np.ones_like(y))
    np.testing.assert_allclose(got, expected, rtol=0, atol=1e-12)


# --------------------------------------------------------------------------- #
# Tie handling
# --------------------------------------------------------------------------- #


@pytest.mark.parametrize("name", sorted(PAVA))
def test_ties_are_pooled(name):
    """Tied x must be aggregated to one weighted point before fitting.

    Guards finding A8: building an interpolant on duplicated abscissae silently
    drops one of the tied points, and which one survives depends on an unstable
    argsort -- so the result is nondeterministic.
    """
    from calibre._core import aggregate_ties

    x, y, w = _case(name)
    ax, ay, aw = aggregate_ties(x, y, w)

    np.testing.assert_allclose(ax, np.asarray(PAVA[name]["agg_x"], dtype=float))
    np.testing.assert_allclose(ay, np.asarray(PAVA[name]["agg_y"], dtype=float))
    np.testing.assert_allclose(aw, np.asarray(PAVA[name]["agg_w"], dtype=float))


@pytest.mark.parametrize("name", sorted(PAVA))
def test_tied_x_output_is_deterministic(name):
    """Same inputs in a different row order must give the same fitted curve."""
    from calibre import IsotonicCalibrator

    x, y, _ = _case(name)
    if len(x) < 2:
        pytest.skip("permutation is meaningless for n < 2")

    grid = np.linspace(x.min(), x.max(), 25)
    base = IsotonicCalibrator().fit(x, y).transform(grid)

    rng = np.random.default_rng(0)
    for _ in range(5):
        p = rng.permutation(len(x))
        got = IsotonicCalibrator().fit(x[p], y[p]).transform(grid)
        np.testing.assert_allclose(got, base, rtol=0, atol=1e-12)


